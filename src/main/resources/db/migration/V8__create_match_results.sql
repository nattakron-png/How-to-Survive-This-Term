CREATE TABLE match_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    team_a_score INT NOT NULL,
    team_b_score INT NOT NULL,
    winner_team_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_match_results_match
        UNIQUE (match_id),

    CONSTRAINT fk_match_results_match
        FOREIGN KEY (match_id)
        REFERENCES matches(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_match_results_winner_team
        FOREIGN KEY (winner_team_id)
        REFERENCES teams(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_match_results_scores
        CHECK (
            team_a_score >= 0
            AND team_b_score >= 0
        )
);

CREATE INDEX idx_match_results_match_id
ON match_results(match_id);

CREATE INDEX idx_match_results_winner_team_id
ON match_results(winner_team_id);